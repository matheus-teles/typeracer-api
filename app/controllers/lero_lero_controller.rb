require 'net/http'
require 'uri'
require 'json'

class LeroLeroController < ApplicationController
  HUGGINGFACE_API_URL = 'https://router.huggingface.co/v1/chat/completions'
  FALLBACK_URL = URI('http://lerolero.miguelborges.com/paragraphs/1')
  DEFAULT_MODEL = 'google/gemma-3-4b-it:fastest'
  PROMPT = <<~TEXT
    Escreva um único parágrafo de lero-lero em português brasileiro, com tom formal,
    burocrático e até cerimonioso, repleto de jargão institucional e referências a
    estudos e comissões fictícias. Responda apenas com o parágrafo.
  TEXT

  def index
    @paragraph = paragraph.split('.').first
    render json: { text: @paragraph }
  rescue StandardError => e
    render json: { error: 'unable to generate text', detail: e.message }, status: :bad_gateway
  end

  private

  def paragraph
    text = huggingface_generation
    text = fallback_paragraph if text.nil? || text.empty?
    raise 'no text generated by any source' if text.nil? || text.empty?

    text.gsub(/<\/*p>/, '').strip
  end

  def huggingface_generation
    token = ENV['HUGGINGFACE_TOKEN'].to_s
    return nil if token.empty?

    uri = URI(HUGGINGFACE_API_URL)
    body = {
      model: ENV.fetch('HUGGINGFACE_MODEL', DEFAULT_MODEL),
      messages: [{ role: 'user', content: PROMPT }],
      max_tokens: 150,
      temperature: 0.9
    }.to_json
    headers = {
      'Authorization' => "Bearer #{token}",
      'Content-Type' => 'application/json'
    }

    response = Net::HTTP.post(uri, body, headers)
    return nil unless response.code.to_i == 200

    JSON.parse(response.body.force_encoding('UTF-8'))
        .dig('choices', 0, 'message', 'content')
        .to_s
        .strip
  rescue StandardError
    nil
  end

  def fallback_paragraph
    response = Net::HTTP.post(FALLBACK_URL, '')
    response.body.force_encoding('UTF-8')
  end
end