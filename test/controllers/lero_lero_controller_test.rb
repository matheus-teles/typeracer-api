require 'test_helper'
require 'net/http'
require 'minitest/mock'

class LeroLeroControllerTest < ActionDispatch::IntegrationTest
  FakeResponse = Struct.new(:code, :body)

  test 'renders text generated by hugging face' do
    ENV['HUGGINGFACE_TOKEN'] = 'hf_test_token'
    content = 'Considerando a conjuntura socioeconômica, a comissão deliberou. A segunda frase, ignorada.'
    fake = FakeResponse.new('200', { choices: [{ message: { content: content } }] }.to_json)

    Net::HTTP.stub :post, fake do
      get lerolero_path
    end

    assert_response :success
    assert_equal(
      'Considerando a conjuntura socioeconômica, a comissão deliberou',
      JSON.parse(response.body)['text']
    )
  ensure
    ENV.delete('HUGGINGFACE_TOKEN')
  end

  test 'falls back to lero lero when no hugging face token is configured' do
    fake = FakeResponse.new('200', '<p>Primeira parte do parágrafo de teste. Segunda parte.</p>')

    Net::HTTP.stub :post, fake do
      get lerolero_path
    end

    assert_response :success
    assert_equal 'Primeira parte do parágrafo de teste', JSON.parse(response.body)['text']
  end

  test 'falls back to lero lero when hugging face errors' do
    ENV['HUGGINGFACE_TOKEN'] = 'hf_test_token'
    failing_hf = FakeResponse.new('500', 'model unavailable')
    lero_lero = FakeResponse.new('200', '<p>Texto de origem alternativa e legível.</p>')

    Net::HTTP.stub :post, proc { |url, _body, headers|
      headers.nil? ? lero_lero : failing_hf
    } do
      get lerolero_path
    end

    assert_response :success
    assert_equal 'Texto de origem alternativa e legível', JSON.parse(response.body)['text']
  ensure
    ENV.delete('HUGGINGFACE_TOKEN')
  end

  test 'returns bad gateway when every source fails' do
    ENV['HUGGINGFACE_TOKEN'] = 'hf_test_token'
    failing_hf = FakeResponse.new('500', 'model unavailable')

    Net::HTTP.stub :post, proc { |url, _body, headers|
      headers.nil? ? raise(IOError, 'lero lero is down') : failing_hf
    } do
      get lerolero_path
    end

    assert_response :bad_gateway
    assert_equal 'unable to generate text', JSON.parse(response.body)['error']
  ensure
    ENV.delete('HUGGINGFACE_TOKEN')
  end
end